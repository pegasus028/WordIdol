#!/usr/bin/env node
// Builds apps-script/Shared.gs (W4): concatenates schema.js, the shared data files and engine.js,
// unchanged, with a source-hash header. Never edit Shared.gs by hand.
//   node tools/build-gs.js          write apps-script/Shared.gs
//   node tools/build-gs.js --check  exit 1 if Shared.gs is missing or stale
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'apps-script', 'Shared.gs');
// Order matters only for readability: every file attaches globals and the engine reads them lazily.
const SOURCES = [
  'schema.js',
  'data/plan.js',
  'data/choices.js',
  'data/rules.js',
  'data/game.js',
  'data/checklist.js',
  'data/coverage.js',
  'data/pool.js',
  'data/why.js',
  'engine.js'
];
const REQUIRED = ['schema.js', 'data/plan.js', 'data/choices.js', 'data/rules.js', 'data/game.js', 'data/checklist.js', 'data/coverage.js', 'engine.js'];

function sources() {
  const out = [];
  for (const rel of SOURCES) {
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) {
      if (REQUIRED.indexOf(rel) >= 0) throw new Error('build-gs: missing required source ' + rel);
      continue;
    }
    out.push({ rel: rel, text: fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') });
  }
  return out;
}

function sourceHash(list) {
  const h = crypto.createHash('sha256');
  for (const s of list) { h.update(s.rel + '\n'); h.update(s.text); h.update('\n\u0000\n'); }
  return h.digest('hex');
}

function build() {
  const list = sources();
  const hash = sourceHash(list);
  const parts = [
    '// WordIdol shared engine — Shared.gs (generated)',
    '// GENERATED by tools/build-gs.js from the WordIdol repo. Do not edit by hand.',
    '// source-hash: ' + hash,
    '// sources: ' + list.map(function (s) { return s.rel; }).join(', '),
    '// Paste this whole file into the Apps Script project as Shared.gs (beside Code.gs and Roster.gs).',
    ''
  ];
  for (const s of list) {
    parts.push('// ===== ' + s.rel + ' =====');
    parts.push(s.text.replace(/\s+$/, ''));
    parts.push('');
  }
  return { text: parts.join('\n') + '\n', hash: hash, files: list.map(function (s) { return s.rel; }) };
}

function currentHash() {
  if (!fs.existsSync(OUT)) return null;
  const m = /^\/\/ source-hash: ([0-9a-f]{64})$/m.exec(fs.readFileSync(OUT, 'utf8'));
  return m ? m[1] : null;
}

function check() {
  const want = sourceHash(sources());
  const have = currentHash();
  const built = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  return { ok: have === want && built === build().text, want: want, have: have };
}

module.exports = { build: build, check: check, sourceHash: sourceHash, sources: sources, SOURCES: SOURCES, OUT: OUT };

if (require.main === module) {
  if (process.argv.indexOf('--check') >= 0) {
    const c = check();
    console.log(c.ok ? 'Shared.gs is up to date (' + c.want.slice(0, 12) + ')' : 'Shared.gs is STALE: have ' + c.have + ', want ' + c.want);
    process.exit(c.ok ? 0 : 1);
  }
  const b = build();
  fs.writeFileSync(OUT, b.text);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + b.text.split('\n').length + ' lines, hash ' + b.hash.slice(0, 12) + ') from ' + b.files.join(', '));
}
